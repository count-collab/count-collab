import { error, json } from "@sveltejs/kit";
import { canManageDashboardMembers } from "$lib/server/dashboard-authorize";
import { regenerateDashboardShareToken } from "$lib/server/dashboards";
import { logger } from "$lib/server/logger";
import { emitRoomRevoked } from "$lib/utils/socket";
import { dashboardIdSchema } from "$lib/utils/validation";
import type { RequestHandler } from "./$types";

export const POST: RequestHandler = async ({ params, locals }) => {
  const idValidation = dashboardIdSchema.safeParse(params.id);
  if (!idValidation.success) {
    throw error(400, "Invalid dashboard ID format");
  }

  const session = await locals.auth();
  if (!session?.user?.id) {
    throw error(401, "Sign in to regenerate the share link");
  }

  // 404 for non-managers so the dashboard's existence is not revealed
  const allowed = await canManageDashboardMembers(session.user.id, params.id);
  if (!allowed) {
    throw error(404, "Dashboard not found");
  }

  const result = await regenerateDashboardShareToken(params.id);
  if (!result.ok) {
    if (result.reason === "not_found") {
      throw error(404, "Dashboard not found");
    }
    throw error(400, "Only private dashboards have a share link");
  }

  // Sockets that joined with the old token or as followers must re-authorize
  emitRoomRevoked("dashboard", params.id);

  logger.info("Dashboard share link regenerated by user", {
    dashboardId: params.id,
    userId: session.user.id,
    removedFollowers: result.removedFollowers,
  });

  return json({
    shareToken: result.shareToken,
    removedFollowers: result.removedFollowers,
  });
};
