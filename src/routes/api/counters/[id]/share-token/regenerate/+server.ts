import { error, json } from "@sveltejs/kit";
import { canManageMembers } from "$lib/server/authorize";
import { regenerateCounterShareToken } from "$lib/server/counters";
import { logger } from "$lib/server/logger";
import { emitRoomRevoked } from "$lib/utils/socket";
import { counterIdSchema } from "$lib/utils/validation";
import type { RequestHandler } from "./$types";

export const POST: RequestHandler = async ({ params, locals }) => {
  const idValidation = counterIdSchema.safeParse(params.id);
  if (!idValidation.success) {
    throw error(400, "Invalid counter ID format");
  }

  const session = await locals.auth();
  if (!session?.user?.id) {
    throw error(401, "Sign in to regenerate the share link");
  }

  // 404 for non-managers so the counter's existence is not revealed
  const allowed = await canManageMembers(session.user.id, params.id);
  if (!allowed) {
    throw error(404, "Counter not found");
  }

  const result = await regenerateCounterShareToken(params.id);
  if (!result.ok) {
    if (result.reason === "not_found") {
      throw error(404, "Counter not found");
    }
    throw error(400, "Only private counters have a share link");
  }

  // Sockets that joined with the old token or as followers must re-authorize
  emitRoomRevoked("counter", params.id);

  logger.info("Counter share link regenerated by user", {
    counterId: params.id,
    userId: session.user.id,
    removedFollowers: result.removedFollowers,
  });

  return json({
    shareToken: result.shareToken,
    removedFollowers: result.removedFollowers,
  });
};
