#!/usr/bin/env node

import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const packageJson = JSON.parse(readFileSync("./package.json", "utf-8"));

let commit = "unknown";
let branch = "unknown";

try {
  commit = execSync("git rev-parse --short HEAD", { encoding: "utf-8" }).trim();
  branch = execSync("git rev-parse --abbrev-ref HEAD", {
    encoding: "utf-8",
  }).trim();
} catch (error) {
  console.warn(
    "Git information not available:",
    error instanceof Error ? error.message : String(error),
  );
}

const buildInfo = {
  version: packageJson.version,
  commit,
  branch,
  buildTime: new Date().toISOString(),
  buildTimestamp: Date.now(),
};

// Write TypeScript module that Vite bundles into the server at compile time
mkdirSync("src/lib/server", { recursive: true });
writeFileSync(
  "src/lib/server/build-info.generated.ts",
  `// Auto-generated by scripts/generate-build-info.js — do not edit\nexport const buildInfo = ${JSON.stringify(buildInfo, null, 2)} as const;\n`,
);

console.log("✓ Build info generated:", buildInfo);
